

// Component


// - A component is like a JavaScript function.
// - It must start with a capital letter and return HTML (JSX) content.
// - Each .jsx file usually has one main component, but we can create multiple components in the same file.
// - JSX means JavaScript + HTML syntax.
// - A component must return a single parent HTML element.
// - If you want to return multiple elements, wrap them inside a fragment tag: <> </>



function Hello() {
  return <h1>Hello World</h1>
}


export default Hello

